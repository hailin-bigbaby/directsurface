async function clickTab(page: Page, id: string) {
  const rect = await page.evaluate(id => (window as any).__PROCUREMENT__.tabRect(id), id)
  expect(rect).toBeTruthy(); await page.mouse.click(rect.x + 25, rect.y + rect.height / 2)
}
async function clickControl(page: Page, key: string) {
  const rect = await page.evaluate(key => {
    const t = (window as any).__PROCUREMENT__
    const ids: Record<string, string> = { save: 'order.save', submit: 'order.submit', reconcile: 'order.reconcile', exportButton: 'data.export', resetButton: 'data.reset' }
    if (!ids[key]) return t[key].paintBounds
    const rect = t.commandToolbar.itemRect(ids[key]); if (!rect) throw Error(`Command is in overflow: ${ids[key]}`)
    const offset = t.commandToolbar.globalOffset; return { ...rect, x: rect.x + offset.x, y: rect.y + offset.y }
  }, key)
  await page.mouse.click(rect.x + rect.width / 2, rect.y + rect.height / 2)
}
